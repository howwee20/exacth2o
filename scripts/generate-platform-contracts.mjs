import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(root, "platform/contracts/capabilities.json");
const sourceText = await readFile(sourcePath, "utf8");
const source = JSON.parse(sourceText);
const identitySchema = JSON.parse(await readFile(
  path.join(root, "platform/contracts/identity.schema.json"),
  "utf8",
));
const operationSchema = JSON.parse(await readFile(
  path.join(root, "platform/contracts/operation.schema.json"),
  "utf8",
));
const checksum = createHash("sha256").update(sourceText).digest("hex");
const capabilities = source.capabilities;

if (
  typeof source.contractVersion !== "string" ||
  !Array.isArray(capabilities) ||
  capabilities.length === 0
) {
  throw new Error("The capability contract is invalid.");
}

if (
  !identitySchema.properties?.experimentAssignment ||
  !identitySchema.required?.includes("potId") ||
  !identitySchema.required?.includes("sensorKey") ||
  !identitySchema.required?.includes("valveKey")
) {
  throw new Error("The canonical identity contract is incomplete.");
}

const operationStates = new Set(
  operationSchema.properties?.executionState?.enum ?? [],
);
for (const state of [
  "planned",
  "queued",
  "claimed",
  "running",
  "completed",
  "completed_unverified",
  "verified",
  "failed",
  "canceled",
]) {
  if (!operationStates.has(state)) {
    throw new Error(`The operation contract is missing state: ${state}`);
  }
}

const seenCapabilities = new Set();
const seenTools = new Set();
for (const capability of capabilities) {
  if (!capability.id || seenCapabilities.has(capability.id)) {
    throw new Error(`Duplicate or missing capability id: ${capability.id}`);
  }
  seenCapabilities.add(capability.id);
  if (capability.assistantTool) {
    if (seenTools.has(capability.assistantTool)) {
      throw new Error(`Duplicate assistant tool: ${capability.assistantTool}`);
    }
    seenTools.add(capability.assistantTool);
  }
}

const controllerCommands = [...new Set(
  capabilities.flatMap((capability) => capability.controllerCommands ?? []),
)].sort();

const json = JSON.stringify(capabilities, null, 2);
const portalOutput = `// Generated by scripts/generate-platform-contracts.mjs. Do not edit.\n` +
  `export const platformContractVersion = ${JSON.stringify(source.contractVersion)} as const;\n` +
  `export const platformContractChecksum = ${JSON.stringify(checksum)} as const;\n` +
  `export const platformCapabilities = ${json} as const;\n` +
  `export type PlatformCapability = typeof platformCapabilities[number];\n` +
  `export type PlatformCapabilityId = PlatformCapability["id"];\n` +
  `export const controllerCommandTypes = ${JSON.stringify(controllerCommands, null, 2)} as const;\n`;

const moduleOutput = `// Generated by scripts/generate-platform-contracts.mjs. Do not edit.\n` +
  `export const platformContractVersion = ${JSON.stringify(source.contractVersion)};\n` +
  `export const platformContractChecksum = ${JSON.stringify(checksum)};\n` +
  `export const platformCapabilities = ${json};\n` +
  `export const controllerCommandTypes = ${JSON.stringify(controllerCommands, null, 2)};\n`;

const outputs = [
  [
    path.join(root, "research-portal/src/generated/platformCapabilities.ts"),
    portalOutput,
  ],
  [
    path.join(root, "supabase/functions/_shared/platform-capabilities.mjs"),
    moduleOutput,
  ],
  [
    path.join(root, "controller-release/control-executor/src/generated/platform-capabilities.mjs"),
    moduleOutput,
  ],
  [
    path.join(root, "controller-release/matt-balena-release-4174753/control-executor/src/generated/platform-capabilities.mjs"),
    moduleOutput,
  ],
];

const checkOnly = process.argv.includes("--check");
const drift = [];
for (const [outputPath, expected] of outputs) {
  const current = await readFile(outputPath, "utf8").catch(() => null);
  if (current !== expected) {
    drift.push(path.relative(root, outputPath));
    if (!checkOnly) await writeFile(outputPath, expected);
  }
}

if (checkOnly && drift.length) {
  throw new Error(`Generated platform contracts are stale: ${drift.join(", ")}`);
}

if (!checkOnly) {
  process.stdout.write(
    `Generated ${outputs.length} consumers for ${source.contractVersion} (${checksum.slice(0, 12)}).\n`,
  );
}
