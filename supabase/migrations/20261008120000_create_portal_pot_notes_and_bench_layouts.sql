-- Pot notes and versioned bench layouts for the portal.
--
-- Additive only. Nothing here changes controller configuration, targets, pairings, calibration,
-- schedules, readings, valve events or the canonical identity tables (physical_positions,
-- research_pots, hardware_bindings are read, never written). Both tables are append-only:
-- a note is corrected by a new note that supersedes it; a layout is changed by a new version.
--
-- Rollback (no other object depends on these): drop table public.portal_bench_layout_versions;
